"""
context_gen.generator: Generates structured agent.md and MCP-compatible agent.json.
"""

from datetime import datetime, timezone
from typing import Any, Dict, List


def generate_agent_json(
    metadata: Dict[str, Any],
    graph: Dict[str, Any],
    tree: str = "",
    project_path: str = ""
) -> Dict[str, Any]:
    """
    Generates structured, MCP-compatible JSON representation of project context.

    Args:
        metadata (Dict[str, Any]): Project metadata from extractor.
        graph (Dict[str, Any]): AST dependency graph.
        tree (str): Visual directory tree.
        project_path (str): Absolute root project path.

    Returns:
        Dict[str, Any]: Exact 12-key MCP context dictionary.
    """
    path_val = project_path or metadata.get("projectPath", "")
    now_iso = datetime.now(timezone.utc).isoformat()

    # Filter entry points: only retain clean file paths
    raw_entries: List[str] = graph.get("entryPoints", [])
    entry_points = [
        e for e in raw_entries
        if not any(token in e for token in ["node ", "npm ", "python ", " "])
    ]

    return {
        "version": "1.0.0",
        "generatedAt": now_iso,
        "projectPath": path_val,
        "overview": metadata.get("overview", ""),
        "techStack": metadata.get("techStack", []),
        "directoryStructure": tree or "",
        "keyFiles": metadata.get("keyFiles", []),
        "dependencies": metadata.get("dependencies", {"production": {}, "development": {}}),
        "dependencyGraph": {
            "nodes": graph.get("nodes", []),
            "edges": graph.get("edges", [])
        },
        "entryPoints": entry_points,
        "utilities": graph.get("utilities", []),
        "scripts": metadata.get("scripts", {})
    }


def generate_agent_md(
    metadata: Dict[str, Any],
    graph: Dict[str, Any],
    tree: str = ""
) -> str:
    """
    Generates human-readable Markdown context document (agent.md) for LLMs.

    Args:
        metadata (Dict[str, Any]): Project metadata from extractor.
        graph (Dict[str, Any]): AST dependency graph.
        tree (str): Visual directory tree.

    Returns:
        str: Formatted Markdown string.
    """
    lines: List[str] = [
        "# Project Context & Architecture Guide",
        "",
        "> Auto-generated by `context-gen-cli` (Python Edition) for AI agent reasoning.",
        "",
        "## Overview",
        metadata.get("overview", "No overview provided."),
        "",
        "## Tech Stack",
    ]

    stack = metadata.get("techStack", [])
    if stack:
        lines.extend([f"- **{tech}**" for tech in stack])
    else:
        lines.append("- Python")

    lines.extend([
        "",
        "## Directory Structure",
        "```",
        tree.strip() if tree else "No directory tree available.",
        "```",
        "",
        "## Key Files & Entry Points",
    ])

    key_files = metadata.get("keyFiles", [])
    if key_files:
        for kf in key_files:
            lines.append(f"- **`{kf['path']}`**: {kf['description']}")
    else:
        lines.append("- No key files detected.")

    lines.extend([
        "",
        "## Module Dependency Graph",
        "",
        "### Entry Points",
    ])

    entry_points = graph.get("entryPoints", [])
    if entry_points:
        for ep in entry_points:
            lines.append(f"- `{ep}`")
    else:
        lines.append("- None detected.")

    lines.extend([
        "",
        "### Core Modules & Utilities",
    ])

    utilities = graph.get("utilities", [])
    if utilities:
        for u in utilities:
            lines.append(f"- `{u}`")
    else:
        lines.append("- None detected.")

    lines.extend([
        "",
        "### Import Relationships (Edges)",
        "```mermaid",
        "graph TD;",
    ])

    edges = graph.get("edges", [])
    if edges:
        for edge in edges:
            source = edge["from"].replace(".", "_").replace("/", "_").replace("-", "_")
            target = edge["to"].replace(".", "_").replace("/", "_").replace("-", "_")
            lines.append(f"  {source}[\"{edge['from']}\"] --> {target}[\"{edge['to']}\"]")
    else:
        lines.append("  %% No internal dependencies detected")

    lines.extend([
        "```",
        ""
    ])

    return "\n".join(lines)


def generate_agent_yaml(
    metadata: Dict[str, Any],
    graph: Dict[str, Any],
    tree: str = "",
    project_path: str = ""
) -> str:
    """
    Generates clean, structured YAML representation of the project context.

    Args:
        metadata (Dict[str, Any]): Project metadata from extractor.
        graph (Dict[str, Any]): AST dependency graph.
        tree (str): Visual directory tree.
        project_path (str): Root project path.

    Returns:
        str: Formatted YAML string.
    """
    now_iso = datetime.now(timezone.utc).isoformat()
    path_val = project_path or metadata.get("projectPath", "")
    overview = metadata.get("overview", "").replace('"', '\\"')

    lines: List[str] = [
        "# Project Architecture & Context Model (YAML)",
        "# Generated automatically by context-gen-cli (Python Edition)",
        "version: \"1.0.0\"",
        f"generated_at: \"{now_iso}\"",
        f"project_path: \"{path_val}\"",
        f"overview: \"{overview}\"",
        "",
        "tech_stack:",
    ]

    for tech in metadata.get("techStack", ["Python"]):
        lines.append(f"  - \"{tech}\"")

    lines.extend([
        "",
        "entry_points:",
    ])
    for ep in graph.get("entryPoints", []):
        lines.append(f"  - \"{ep}\"")

    lines.extend([
        "",
        "utilities:",
    ])
    for u in graph.get("utilities", []):
        lines.append(f"  - \"{u}\"")

    lines.extend([
        "",
        "key_files:",
    ])
    for kf in metadata.get("keyFiles", []):
        desc = kf['description'].replace('"', '\\"')
        lines.append(f"  - path: \"{kf['path']}\"")
        lines.append(f"    description: \"{desc}\"")

    lines.extend([
        "",
        "dependency_edges:",
    ])
    for edge in graph.get("edges", []):
        lines.append(f"  - from: \"{edge['from']}\"")
        lines.append(f"    to: \"{edge['to']}\"")
        lines.append(f"    type: \"{edge.get('type', 'import')}\"")

    lines.append("")
    return "\n".join(lines)

